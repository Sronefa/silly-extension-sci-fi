// Core tabs: Bridge (overview), Manifest (cargo and gear), Dossier (missions, standing), Log.
import { registerTab, registerWidget, registerActions, gauge, btn, ask, confirmAsk } from './hud.js';
import { S, commit, addLog, fmtDate, locationLabel, cargoUsed, cargoCap, shipClass, currentSystem } from '../core/state.js';
import { runCommand, runBlock, advanceTime, needStatuses } from '../systems/sim.js';
import { esc, fmtInt, uid } from '../core/util.js';
import { toast, toInput } from '../core/st.js';
import { NEEDS, SHIP_SYSTEMS, SHIP_WEAPONS, FACTIONS } from '../data/catalog.js';
import { CRAFT_CLASSES } from '../data/chargen.js';
import { hasFx } from '../systems/character.js';
import { isDown } from '../systems/body.js';
import { factionById, SECURITY_LABELS } from '../systems/galaxy.js';
import { blip } from './sfx.js';

/** Runs a command typed or generated by the UI and reports the result. */
function exec(line, { quiet = false } = {}) {
    const r = runCommand(line);
    if (!r.ok) { toast('warning', r.text); blip('error'); return r; }
    if (!quiet) toast('info', r.text);
    commit('ui');
    return r;
}

const q = (s) => `"${String(s).replace(/"/g, "'")}"`;

function defineWidgets() {
    registerWidget({
        id: 'position', title: () => 'Position', render(st) {
            const sys = currentSystem();
            const fac = factionById(sys.faction);
            const alertBtn = (lvl, label) => `<button type="button" class="sf-btn sf-alert-btn ${lvl}${st.alert === lvl ? ' active' : ''}" data-sf="alert" data-level="${lvl}">${label}</button>`;
            return `<div class="sf-loc-main"><i class="fa-solid fa-location-crosshairs"></i> ${esc(locationLabel(st))}</div>
            <div class="sf-loc-sub"><span style="color:${fac.color}">${esc(fac.name)}</span> · ${SECURITY_LABELS[sys.security]} security · ${esc(sys.star.label)}</div>
            <div class="sf-actions">
                ${btn('edit', 'Set location', { icon: 'fa-pen', data: { cmd: 'location', label: 'Where are you? (leave empty to clear)', text: '1' } })}
                ${st.loc.docked ? btn('run', 'Undock', { icon: 'fa-arrow-up-from-bracket', data: { cmd: 'undock' } }) : btn('run', 'Dock', { icon: 'fa-anchor', data: { cmd: 'dock' } })}
            </div>
            <div class="sf-alert-row">${alertBtn('green', 'Green')}${alertBtn('yellow', 'Yellow')}${alertBtn('red', 'Red alert')}</div>`;
        },
    });
    registerWidget({
        id: 'ship', when: (st) => !!st.ship, title: (st) => st.ship.name, render(st) {
            const ship = st.ship;
            const weapons = ship.weapons.map(w => `<span class="sf-tag">${esc(SHIP_WEAPONS[w.id]?.name ?? w.id)}${w.ammo != null ? ` · ${w.ammo}` : ''}</span>`).join('') || '<span class="sf-dim">Unarmed</span>';
            return `<div class="sf-sub">${esc(shipClass(st).name)} ${btn('ship-rename', '', { icon: 'fa-pen', cls: 'ghost', title: 'Rename ship' })}</div>
            ${gauge('Hull', ship.hull, ship.maxHull, { edit: 'hull' })}
            ${gauge('Shields', ship.shields, ship.maxShields, { edit: 'shields' })}
            ${gauge('Fuel', ship.fuel, ship.maxFuel, { edit: 'fuel', text: `${Math.round(ship.fuel * 10) / 10}/${ship.maxFuel}` })}
            ${gauge('Cargo', cargoUsed(st), ship.cargoCap, { cls: 'info', text: `${cargoUsed(st)}/${ship.cargoCap} t` })}
            <div class="sf-stat-grid">
                <div class="sf-stat sf-editable" data-sf="edit" data-cmd="supplies" data-label="Supplies (crew-days)"><small>Supplies</small><b>${Math.round(ship.supplies)}</b><small>crew-days</small></div>
                <div class="sf-stat sf-editable" data-sf="edit" data-cmd="parts" data-label="Spare parts"><small>Spare parts</small><b>${ship.parts}</b><small>units</small></div>
                <div class="sf-stat"><small>Armor</small><b>${ship.armor}</b><small>rating</small></div>
                <div class="sf-stat"><small>Crew</small><b>${st.crew.length + 1}</b><small>of ${ship.crewMax}</small></div>
            </div>
            <div class="sf-sub">Weapons</div><div class="sf-tags">${weapons}</div>`;
        },
    });
    registerWidget({
        id: 'systems', when: (st) => !!st.ship, title: () => 'Ship systems',
        render: (st) => SHIP_SYSTEMS.map(s => gauge(s.name, st.ship.systems[s.id], 100, { text: `${Math.round(st.ship.systems[s.id])}%`, edit: `system ${s.id}` })).join(''),
    });
    registerWidget({
        id: 'hangar', when: (st) => st.craft.length > 0, title: () => 'Hangar',
        render: (st) => st.craft.map(c => {
            const cls = CRAFT_CLASSES[c.classId];
            return `<div class="sf-craft"><div class="sf-loc-main"><i class="fa-solid ${c.kind === 'mech' ? 'fa-robot' : 'fa-jet-fighter'}"></i> ${esc(c.name)}</div>
                <div class="sf-loc-sub">${esc(cls?.role ?? c.kind)} · armor ${c.armor} · evasion ${cls?.evasion ?? '?'}</div>
                ${gauge('Frame', c.hull, c.maxHull)}${gauge('Shields', c.shields, c.maxShields)}
                <div class="sf-tags">${(cls?.weapons ?? []).map(w => `<span class="sf-tag">${esc(w)}</span>`).join('')}</div>
                <small class="sf-dim">${esc(cls?.traits ?? '')}</small></div>`;
        }).join(''),
    });
    registerWidget({
        id: 'noship', when: (st) => !st.ship, title: () => 'No vessel',
        render: () => `<div class="sf-dim">You do not own a starship. Travel by booking passage on the Nav tab, sign on with a crew, or find a way to get a hull of your own.</div>`,
    });
    registerWidget({
        id: 'vitals', title: (st) => st.captain.name, render(st) {
            const cap = st.captain;
            const statuses = needStatuses(st);
            const injuries = cap.injuries.map(i => `<li class="sf-row"><span class="sf-sev ${i.severity}">${esc(i.severity)}</span><span class="sf-grow">${esc(i.name)}</span>${btn('injury-heal', '', { icon: 'fa-check', cls: 'ghost', data: { name: i.name }, title: 'Mark healed' })}</li>`).join('');
            return `${isDown(cap) ? `<div class="sf-downed"><b>DOWNED</b><span>Unconscious and dying. Someone has to stabilise you.</span>
                <div class="sf-actions">${btn('vitals-stable', 'Stabilised', { icon: 'fa-heart-pulse', cls: 'primary' })}${btn('vitals-die', 'Died', { icon: 'fa-skull' })}</div></div>` : ''}
            ${gauge('Health', cap.health, cap.maxHealth, { edit: 'health' })}
            ${gauge('Stress', cap.stress, 100, { invert: true, edit: 'stress', text: `${Math.round(cap.stress)}%` })}
            ${NEEDS.map(n => gauge(n.name, cap.needs[n.id], 100, { edit: n.id, text: `${Math.round(cap.needs[n.id])}%` })).join('')}
            ${hasFx(cap, 'craving') ? gauge('Craving', cap.craving, 100, { invert: true, edit: 'craving', text: `${Math.round(cap.craving)}%` }) : ''}
            ${statuses.length ? `<div class="sf-warn-line"><i class="fa-solid fa-triangle-exclamation"></i> ${esc(statuses.join(' · '))}</div>` : ''}
            <div class="sf-sub">Injuries ${btn('injury-add', '', { icon: 'fa-plus', cls: 'ghost', title: 'Add injury' })}</div>
            <ul class="sf-list">${injuries || '<li class="sf-dim">None recorded</li>'}</ul>`;
        },
    });
    registerWidget({
        id: 'clock', title: () => 'Clock',
        render: (st) => `<div class="sf-clock">${esc(fmtDate(st.minutes))}</div><div class="sf-actions">
            ${btn('run', '+10 min', { icon: 'fa-clock', data: { cmd: 'time +10m' } })}
            ${btn('run', '+30 min', { icon: 'fa-clock', data: { cmd: 'time +30m' } })}
            ${btn('run', '+1 h', { icon: 'fa-clock', data: { cmd: 'time +1h' } })}
            ${btn('edit', 'Custom', { icon: 'fa-pen', data: { cmd: 'time', label: 'Advance time (e.g. +3h, +45m, +2d)' } })}
        </div>`,
    });

    const row = (kind, it) => `<li class="sf-row">
        <span class="sf-grow">${esc(it.name)}</span>
        ${btn('stack', '', { icon: 'fa-minus', cls: 'ghost', data: { kind, name: it.name, op: 'remove' } })}
        <b class="sf-qty">${it.qty}</b>
        ${btn('stack', '', { icon: 'fa-plus', cls: 'ghost', data: { kind, name: it.name, op: 'add' } })}
    </li>`;
    registerWidget({
        id: 'account', title: () => 'Account',
        render: (st) => `<div class="sf-credits sf-editable" data-sf="edit" data-cmd="credits" data-label="Credits"><small>Balance</small><b>${fmtInt(st.captain.credits)} cr</b></div>
            ${st.captain.debt ? `<div class="sf-credits debt sf-editable" data-sf="edit" data-cmd="debt" data-label="Debt"><small>Outstanding debt</small><b>${fmtInt(st.captain.debt)} cr</b></div>` : ''}`,
    });
    registerWidget({
        id: 'cargo', title: (st) => (st.ship ? 'Cargo hold' : 'Hauled goods'),
        render: (st) => `${gauge('Capacity', cargoUsed(st), cargoCap(st), { cls: 'info', text: `${cargoUsed(st)}/${cargoCap(st)} t` })}
            <ul class="sf-list">${st.cargo.map(c => row('cargo', c)).join('') || '<li class="sf-dim">Hold is empty</li>'}</ul>
            <div class="sf-actions">${btn('stack-new', 'Add cargo', { icon: 'fa-box', data: { kind: 'cargo' } })}</div>`,
    });
    registerWidget({
        id: 'gear', title: () => 'Personal gear',
        render: (st) => `<ul class="sf-list">${st.captain.inventory.map(i => row('item', i)).join('') || '<li class="sf-dim">Nothing carried</li>'}</ul>
            <div class="sf-actions">${btn('stack-new', 'Add item', { icon: 'fa-toolbox', data: { kind: 'item' } })}</div>`,
    });

    registerWidget({
        id: 'missions', title: () => 'Missions', render(st) {
            const missions = st.missions.map(m => `<li class="sf-row sf-mission ${m.status}">
                <span class="sf-grow"><b>${esc(m.title)}</b>${m.reward ? ` <span class="sf-dim">${fmtInt(m.reward)} cr</span>` : ''}${m.notes ? `<br><small class="sf-dim">${esc(m.notes)}</small>` : ''}</span>
                ${m.status === 'active'
                ? btn('mission', '', { icon: 'fa-check', cls: 'ghost', data: { op: 'done', title: m.title }, title: 'Complete' }) + btn('mission', '', { icon: 'fa-xmark', cls: 'ghost', data: { op: 'fail', title: m.title }, title: 'Fail' })
                : `<span class="sf-tag">${m.status}</span>` + btn('mission', '', { icon: 'fa-trash', cls: 'ghost', data: { op: 'drop', title: m.title }, title: 'Remove' })}
            </li>`).join('');
            return `<ul class="sf-list">${missions || '<li class="sf-dim">No contracts on file</li>'}</ul><div class="sf-actions">${btn('mission-add', 'New mission', { icon: 'fa-plus' })}</div>`;
        },
    });
    registerWidget({
        id: 'factions', title: () => 'Faction standing',
        render: (st) => FACTIONS.map(f => {
            const v = st.reputation[f.id] ?? 0;
            return `<div class="sf-rep sf-editable" data-sf="edit" data-cmd="rep ${f.id}" data-label="${esc(f.name)} standing (-100 to 100)">
                <span class="sf-rep-name" style="color:${f.color}">${esc(f.name)}</span>
                <div class="sf-rep-bar"><span class="${v < 0 ? 'neg' : 'pos'}" style="width:${Math.abs(v) / 2}%"></span></div>
                <span class="sf-gauge-val">${v > 0 ? '+' : ''}${v}</span>
            </div>`;
        }).join(''),
    });
    registerWidget({
        id: 'contacts', title: () => 'Contacts', render(st) {
            const contacts = st.contacts.map(c => `<li class="sf-row"><span class="sf-grow"><b>${esc(c.name)}</b>${c.notes ? ` <small class="sf-dim">${esc(c.notes)}</small>` : ''}</span>
                <span class="sf-editable sf-tag" data-sf="edit" data-cmd="contact ${esc(q(c.name))}" data-label="Standing with ${esc(c.name)}">${c.standing > 0 ? '+' : ''}${c.standing}</span>
                ${btn('contact-remove', '', { icon: 'fa-trash', cls: 'ghost', data: { id: c.id } })}</li>`).join('');
            return `<ul class="sf-list">${contacts || '<li class="sf-dim">No known contacts</li>'}</ul><div class="sf-actions">${btn('contact-add', 'Add contact', { icon: 'fa-plus' })}</div>`;
        },
    });
    registerWidget({
        id: 'trackers', title: () => 'Custom trackers', render(st) {
            const trackers = st.trackers.map(t => `<div class="sf-row">${gauge(t.name, t.value, t.max, { cls: 'info', edit: `tracker ${q(t.name)}` })}${btn('tracker-remove', '', { icon: 'fa-trash', cls: 'ghost', data: { id: t.id } })}</div>`).join('');
            return `${trackers || '<div class="sf-dim">Track anything: heat, bounty, oxygen, a countdown.</div>'}<div class="sf-actions">${btn('tracker-add', 'New tracker', { icon: 'fa-plus' })}</div>`;
        },
    });
    registerWidget({
        id: 'console', title: () => 'Command console',
        render: () => `<div class="sf-console"><span>&gt;</span><input class="sf-input sf-console-in" placeholder="hull -20; time +2h; cargo add &quot;Water&quot; 5" autocomplete="off" autocapitalize="off"></div>
            <div class="sf-actions">${btn('console-run', 'Execute', { icon: 'fa-terminal', cls: 'primary' })}${btn('log-add', 'Log entry', { icon: 'fa-pen' })}${btn('status-to-chat', 'Status to chat', { icon: 'fa-share' })}</div>
            <small class="sf-dim">Same commands the AI uses. Separate several with a semicolon.</small>`,
    });
    registerWidget({
        id: 'shiplog', title: () => "Ship's log",
        render: (st) => `<ul class="sf-loglist">${st.log.map(l => `<li class="sf-log ${l.kind}"><time>${esc(fmtDate(l.t))}</time><span>${esc(l.text)}</span></li>`).join('') || '<li class="sf-dim">No entries</li>'}</ul>`,
    });
}

export function initCoreTabs() {
    defineWidgets();
    registerTab({ id: 'status', label: 'Status', icon: 'fa-gauge-high', order: 10, widgets: ['position', 'vitals', 'body', 'activities', 'party', 'clock', 'checkpoints', 'encounter'] });
    registerTab({ id: 'ship', label: 'Ship', icon: 'fa-rocket', order: 16, widgets: ['ship', 'systems', 'hangar', 'noship'] });
    registerTab({ id: 'gear', label: 'Gear', icon: 'fa-boxes-stacked', order: 30, widgets: ['account', 'loadout', 'gear', 'cargo'] });
    registerTab({ id: 'dossier', label: 'Dossier', icon: 'fa-id-card', order: 40, widgets: ['missions', 'factions', 'contacts', 'trackers', 'archive'], badge: (st) => st.missions.filter(m => m.status === 'active').length || '' });
    registerTab({ id: 'log', label: 'Log', icon: 'fa-terminal', order: 90, widgets: ['console', 'shiplog'] });

    registerActions({
        async edit(el) {
            const cmd = el.dataset.cmd;
            const isText = el.dataset.text === '1';
            const v = await ask(`${el.dataset.label ?? cmd}${isText ? '' : ': type +N, -N or an exact value'}`);
            if (v === null || v === undefined || v === false) return;
            const val = String(v).trim();
            if (!val && !isText) return;
            exec(isText ? `${cmd} ${q(val)}` : `${cmd} ${val}`);
        },
        run(el) { exec(el.dataset.cmd); },
        alert(el) {
            exec(`alert ${el.dataset.level}`, { quiet: true });
            if (el.dataset.level === 'red') blip('alert');
        },
        async 'ship-rename'() {
            const st = S();
            const v = await ask('Ship name', st.ship.name);
            if (!v) return;
            st.ship.name = String(v).trim();
            commit('ui');
        },
        async 'injury-add'() {
            const name = await ask('Injury (e.g. Fractured rib)');
            if (!name) return;
            const sev = await ask('Severity: minor, moderate, severe or critical', 'moderate');
            exec(`injury add ${q(name)} ${sev || 'minor'}`);
        },
        'injury-heal'(el) { exec(`injury heal ${q(el.dataset.name)}`); },
        async 'crew-add'() {
            const name = await ask('Crew member name');
            if (!name) return;
            const role = await ask('Role (Pilot, Engineer, Gunner, Medic…)', 'Engineer');
            exec(`crew add ${q(name)} ${q(role || 'Crew')}`);
        },
        async 'crew-remove'(el) {
            if (await confirmAsk('Remove crew member?', el.dataset.name)) exec(`crew remove ${q(el.dataset.name)}`);
        },
        stack(el) { exec(`${el.dataset.kind} ${el.dataset.op} ${q(el.dataset.name)} 1`, { quiet: true }); },
        async 'stack-new'(el) {
            const name = await ask(el.dataset.kind === 'cargo' ? 'Cargo name' : 'Item name');
            if (!name) return;
            const qty = await ask('Quantity', '1');
            exec(`${el.dataset.kind} add ${q(name)} ${Number(qty) || 1}`);
        },
        async 'mission-add'() {
            const title = await ask('Mission title');
            if (!title) return;
            const reward = await ask('Reward in credits (0 for none)', '0');
            exec(`mission add ${q(title)} reward ${Number(reward) || 0}`);
        },
        mission(el) { exec(`mission ${el.dataset.op} ${q(el.dataset.title)}`); },
        async 'contact-add'() {
            const name = await ask('Contact name');
            if (!name) return;
            const notes = await ask('Who are they? (optional)', '');
            const st = S();
            st.contacts.push({ id: uid('ct'), name: String(name).trim(), standing: 0, notes: String(notes || '').trim() });
            commit('ui');
        },
        'contact-remove'(el) {
            const st = S();
            st.contacts = st.contacts.filter(c => c.id !== el.dataset.id);
            commit('ui');
        },
        async 'tracker-add'() {
            const name = await ask('Tracker name');
            if (!name) return;
            const max = await ask('Maximum value', '100');
            exec(`tracker ${q(name)} 0 max ${Number(max) || 100}`);
        },
        'tracker-remove'(el) {
            const st = S();
            st.trackers = st.trackers.filter(t => t.id !== el.dataset.id);
            commit('ui');
        },
        'console-run'(el) {
            const input = el.closest('.sf-panel-body')?.querySelector('.sf-console-in');
            const text = input?.value.trim();
            if (!text) return;
            const results = runBlock(text);
            const bad = results.filter(r => !r.ok);
            const good = results.filter(r => r.ok);
            if (good.length) toast('info', good.map(r => r.text).join(' · '));
            if (bad.length) { toast('warning', bad.map(r => r.text).join(' · ')); blip('error'); }
            commit('ui');
        },
        async 'log-add'() {
            const text = await ask("Ship's log entry");
            if (!text) return;
            addLog(String(text), 'story');
            commit('ui');
        },
        'status-to-chat'() {
            const st = S();
            toInput(`*${st.captain.name} checks the console. ${locationLabel(st)}.${st.ship ? ` Hull ${Math.round(st.ship.hull)}/${st.ship.maxHull}, fuel ${Math.round(st.ship.fuel)}/${st.ship.maxFuel}.` : ''} ${fmtInt(st.captain.credits)} credits.*`);
        },
    });
    // Enter runs the console.
    document.addEventListener('keydown', (ev) => {
        if (ev.key === 'Enter' && ev.target?.classList?.contains('sf-console-in')) {
            ev.preventDefault();
            ev.target.closest('.sf-panel-body')?.querySelector('[data-sf="console-run"]')?.click();
        }
    });
}

export { exec, advanceTime };
